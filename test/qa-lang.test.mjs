// T6 (spec 022, R19, C2 y C3) — los artefactos del QA salen en el idioma del contenido (specLang, o el
// de la interfaz si no hay), y los prompts que declaran ${LANGUAGE} no llevan frases fijas en español.

import test from 'node:test';
import assert from 'node:assert/strict';
import { runQaAgent } from '../lib/qaagent.mjs';
import { buildQaPlan, buildBrowserTests } from '../lib/qa.mjs';
import { renderReplaySpec } from '../lib/qa/browser.mjs';

const SPANISH = /ÚLTIMO PASO|Te quedan|sin observaciones|\bPaso \d|acción:|resultado:|veredicto final/;

// ── C3: el agente QA habla al modelo en inglés ──────────────────────────────────────────────────
test('C3: los mensajes del loop del agente QA van en inglés', async () => {
  const seen = [];
  let n = 0;
  const chatImpl = async (cfg, req) => {
    seen.push(req.system, req.user);
    return ++n === 1 ? JSON.stringify({ thought: 't', action: { type: 'http', path: '/x' } }) : JSON.stringify({ done: true, verdicts: [] });
  };
  await runQaAgent({ cfg: {}, surface: 'api', baseUrl: 'http://x', plan: 'p', executor: async () => ({ ok: true }), chatImpl, maxSteps: 2, ccr: false, language: 'English' });
  for (const text of seen) assert.equal(SPANISH.test(text), false, text.slice(-400));
  assert.match(seen.join('\n'), /Step 1/);
  assert.match(seen.at(-1), /LAST STEP/);
});

// ── C2: artefactos según specLang ───────────────────────────────────────────────────────────────
const context = { id: '001-x', files: { 'spec.md': '- **R1** — WHEN x THE SYSTEM SHALL y.\n' } };

test('C2: test-plan.md en inglés con specLang en y en español con specLang es', () => {
  const en = buildQaPlan(context, null, { specLang: 'en' });
  assert.match(en, /# QA plan — 001-x/);
  assert.match(en, /Traceability/);
  assert.equal(/Trazabilidad|Preguntas QA|Pendiente|pendiente/.test(en), false, en);
  const es = buildQaPlan(context, null, { specLang: 'es' });
  assert.match(es, /# Plan QA — 001-x/);
  assert.match(es, /Trazabilidad/);
});

test('C2: el plan sin requisitos también se localiza', () => {
  const en = buildQaPlan({ id: '002', files: { 'spec.md': 'nada' } }, null, { specLang: 'English' });
  assert.match(en, /No R# requirements/);
});

test('C2: los comentarios del spec Playwright generado siguen specLang', () => {
  const en = buildBrowserTests(context, {}, { specLang: 'en' });
  assert.match(en, /\/\/ Generated by chalc qa/);
  assert.match(en, /\/\/ Missing path or observable result/);
  assert.match(buildBrowserTests(context, {}, { specLang: 'es' }), /\/\/ Generado por chalc qa/);
});

test('C2: el spec de réplica del agente sigue specLang', () => {
  const steps = [{ action: { type: 'browser', requirement: 'R1', steps: [{ op: 'inspect' }, { op: 'raro' }] }, observation: { ok: true } }];
  const en = renderReplaySpec({ specId: '001', baseUrl: 'http://x', steps, specLang: 'en' });
  assert.match(en, /\/\/ Generated by chalc qa --agent/);
  assert.match(en, /\/\/ inspect \(no assertion\)/);
  assert.match(en, /\/\/ op not reproducible/);
  assert.match(renderReplaySpec({ specId: '001', baseUrl: 'http://x', steps: [], specLang: 'en' }), /did not run reproducible browser steps/);
  assert.match(renderReplaySpec({ specId: '001', baseUrl: 'http://x', steps, specLang: 'es' }), /\/\/ inspect \(sin aserción\)/);
});

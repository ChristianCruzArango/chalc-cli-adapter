// T12 (spec 022, R19, C2) — los artefactos de QA salen en el idioma del contenido del proyecto (el que
// guarda `.chalc.json`), no en el de la interfaz ni siempre en español.

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tempDir } from './helpers/tmpdir.mjs';
import { writeQaPlan, writeBrowserTests } from '../lib/qa.mjs';
import { writeQaReplaySpecArtifact } from '../lib/qaflow.mjs';

const context = { id: '001-x', files: { 'spec.md': '' } };

async function project(t, lang) {
  const dir = await tempDir(t);
  await writeFile(join(dir, '.chalc.json'), JSON.stringify({ lang }));
  return dir;
}

for (const [lang, plan, replay] of [['en', /^# QA plan/, /Generated by chalc qa/], ['es', /^# Plan QA/, /Generado por chalc qa/]]) {
  test(`C2: con .chalc.json lang=${lang} el plan, los tests y la réplica salen en ${lang}`, async (t) => {
    const dir = await project(t, lang);
    const { path } = await writeQaPlan(dir, context, null);
    assert.match(await readFile(path, 'utf8'), plan);
    const tests = await readFile(await writeBrowserTests(dir, context, {}), 'utf8');
    const other = lang === 'en' ? /Generado por chalc/ : /Generated by chalc/;
    assert.doesNotMatch(tests, other);
    const { path: rp } = await writeQaReplaySpecArtifact(dir, context, 'http://127.0.0.1:1', { steps: [] });
    assert.match(await readFile(rp, 'utf8'), replay);
  });
}
